# 报告生成（可选：生成 markdown 数据集清单，便于评审与验收）
# ======================================================================

def write_dataset_report(path):
    """把数据集统计与用例清单写为 markdown 报告。"""
    cases = CASES()
    stats = dataset_stats()
    lines = [
        "# EchoSQL(MiniDB) 黑盒测试数据集报告",
        "",
        "> 生成方式：`python tests/test_blackbox.py --report <path>`（或调用 "
        "`blackbox_dataset.write_dataset_report`）。",
        "",
        "## 规模统计",
        "",
        "| 指标 | 数值 |",
        "| --- | --- |",
        "| 总用例数 | %d |" % stats["total"],
        "| 边界用例数 | %d |" % stats["boundary"],
        "| 边界占比 | %.2f%% |" % (stats["boundary_ratio"] * 100),
        "| 要求：总用例 >= 200 | %s |" % ("满足" if stats["total"] >= 200 else "不满足"),
        "| 要求：边界占比 >= 5%% | %s |" % (
            "满足" if stats["boundary_ratio"] >= 0.05 else "不满足"),
        "",
        "## 分层分布",
        "",
        "| 层 | 用例数 |",
        "| --- | --- |",
    ]
    for layer, n in sorted(stats["by_layer"].items()):
        lines.append("| %s | %d |" % (layer, n))
    lines += ["", "## 类别分布", "", "| 类别 | 用例数 |", "| --- | --- |"]
    for cat, n in sorted(stats["by_category"].items()):
        lines.append("| %s | %d |" % (cat, n))
    lines += ["", "## 边界用例清单（%d 条）" % stats["boundary"], "",
              "| 编号 | 类别 | 标题 |", "| --- | --- | --- |"]
    for c in cases:
        if c["boundary"]:
            lines.append("| %s | %s | %s |" % (c["id"], c["category"], c["title"]))
    lines += ["", "## 全部用例清单（%d 条）" % stats["total"], "",
              "| 编号 | 层 | 类别 | 边界 | 标题 | 需求追溯 |", "| --- | --- | --- | --- | --- | --- |"]
    for c in cases:
        lines.append("| %s | %s | %s | %s | %s | %s |"
                     % (c["id"], c["layer"], c["category"],
                        "是" if c["boundary"] else "-", c["title"], c["ref"]))
    lines.append("")
    with open(path, "w", encoding="utf-8") as fp:
        fp.write("\n".join(lines))
    return path


