"""EchoSQL(MiniDB) 黑盒测试数据集（P6：黑盒 / 系统测试）。

设计原则
--------
- **黑盒视角**：用例只描述「输入 SQL / 调用方式 → 可观察的输出或错误」，
  不依赖任何内部实现（不引用 lexer/parser/planner/存储内部结构）。
  期望值均依据需求（SRS FR-1.x / FR-2.x / FR-3.x、grammar.md、TC-E2E-01~05）
  与实际可观察行为给出。
- **数据驱动**：每条用例是一条记录（dict），由 tests/test_blackbox.py 中的
  黑盒驱动器逐条执行并断言；数据集与脚本分离、脚本内嵌引用，便于评审与追溯。
- **规模要求**：总用例数 >= 200，其中边界案例占比 >= 5%。
  模块提供 dataset_stats() 供执行器审计；test_blackbox.py 会对该要求做硬断言。

记录字段（expect 为期望描述）
-----------------------------
    id        用例编号（全局唯一，BB-xxxx）
    layer     engine | cli | web        —— 黑盒入口层
    category  用例类别（中文，用于报告分组）
    ref       需求/规格追溯（SRS FR / grammar / TC 编号）
    title     用例标题（一句话描述）
    boundary  是否边界案例（True/False）
    setup     前置语句列表（engine/web 在动作前执行，须全部成功）
    action    被测动作：SQL 字符串（engine）；None=无动作（纯检查类）；
               dict={"api": 门面方法名, "args": [...]}（engine 目录类）；
               脚本文本（cli）；HTTP 动作 dict（web，见下）
    expect    期望结果 dict（各层键说明见下）
    mode      engine 层的执行模式：sql（默认，db.execute）|
              script（db.execute_script）| persist（重启持久化场景）

expect 键（engine 层）
    empty         动作返回 None（空输入），仅此一项
    error         期望抛出的错误 kind（如 UnknownTable / RowTooLarge）
    error_has     错误文本应包含的子串
    kind          成功结果的 kind（CREATE/INSERT/SELECT/DELETE）
    rows / columns / rows_affected / message_has
    api_return    api 动作（action 为 dict）的返回值断言
    persist       dict：重启持久化场景配置，见下
    then_sql / then_rows / then_columns   动作后的二次校验 SELECT
                  （错误场景下也执行，用于验证副作用保留）

persist 配置（expect["persist"]，engine 层重启场景）
    pre_close_api   关闭前调用的门面 API（如删表）
    reopen_insert   重启后执行的写入 SQL
    check2_sql / check2_rows   重启续写后的二次校验

记录级检查字段（engine/web 层，动作后断言）
    check_tables               db.tables() 应等于的列表
    check_info_columns / check_info_types   首表列名 / 列类型
    check_stats_has            db.stats() 应包含的键
    check_stats_range          hit_rate 应处于的闭区间
    check_tables_after_reopen  重启后（persist 场景）tables() 应等于的列表
    check_api_tables_names     web：/api/tables 返回的表名列表

expect 键（cli 层）：rc（进程退出码）、stdout_has / stdout_has_not
expect 键（web 层）：status、json_has（响应 JSON 逐键相等比较）

边界案例标记原则：输入位于规格边界（空输入、长度/范围极值、行容量上限、
跨页、包含/不包含的阈值比较、语法极限如深层括号与长链、非法字符集外输入等）。
"""

# ======================================================================
# 用例构造器（校验 id 唯一性）
# ======================================================================

_SEEN_IDS = set()


def TC(cid, category, ref, title, action, expect, setup=None, boundary=False,
       layer="engine", mode="sql", **extra):
    """构造一条黑盒测试用例记录（dict）。"""
    if cid in _SEEN_IDS:
        raise ValueError("duplicate black-box case id: %r" % cid)
    _SEEN_IDS.add(cid)
    record = {
        "id": cid,
        "layer": layer,
        "category": category,
        "ref": ref,
        "title": title,
        "action": action,
        "expect": expect,
        "setup": list(setup or []),
        "boundary": bool(boundary),
        "mode": mode,
    }
    record.update(extra)
    return record


def CASES():
    """返回全部黑盒测试用例（构建时校验 id 唯一性）。"""
    return list(_build())


def dataset_stats():
    """审计统计：总数 / 边界数 / 边界占比 / 各层与各类别计数。

    供 test_blackbox.py 的审计用例做硬断言（>=200 且边界占比 >=5%）。
    """
    cases = CASES()
    total = len(cases)
    boundary = sum(1 for c in cases if c["boundary"])
    by_layer = {}
    by_category = {}
    for c in cases:
        by_layer[c["layer"]] = by_layer.get(c["layer"], 0) + 1
        by_category[c["category"]] = by_category.get(c["category"], 0) + 1
    return {
        "total": total,
        "boundary": boundary,
        "boundary_ratio": boundary / total if total else 0.0,
        "by_layer": by_layer,
        "by_category": by_category,
    }


def boundary_ids():
    return [c["id"] for c in CASES() if c["boundary"]]


